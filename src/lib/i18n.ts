export function t(key: string, lang: string = 'en'): string {
  const langTable = TRANSLATIONS[lang as LanguageCode] || TRANSLATIONS.en;
  return langTable[key] || TRANSLATIONS.en[key] || key;
}

export function useLanguage() {
  const [lang, setLang] = useState<string>(() => {
    return localStorage.getItem('skillgo_active_language_v1') || 'en';
  });

  useEffect(() => {
    const handleStorage = () => {
      setLang(localStorage.getItem('skillgo_active_language_v1') || 'en');
    };
    window.addEventListener('storage', handleStorage);
    window.addEventListener('skillgo-lang-change', handleStorage as EventListener);
    return () => {
      window.removeEventListener('storage', handleStorage);
      window.removeEventListener('skillgo-lang-change', handleStorage as EventListener);
    };
  }, []);

  return lang;
}
